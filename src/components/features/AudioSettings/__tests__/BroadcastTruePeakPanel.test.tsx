import { act, cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { listen } from '@tauri-apps/api/event';
import { broadcastTruePeakApi, type BroadcastTruePeakStatus } from '@/api/broadcastTruePeak';
import { BroadcastTruePeakPanel } from '../BroadcastTruePeakPanel';
import { message } from '@/i18n/messages';
const fixture = (enabled = false, addedLatencySamples = enabled ? 48 : 0, applied = enabled): BroadcastTruePeakStatus => ({
    config: { enabled, ceilingDb: -3, releaseMs: 150 }, running: true, pending: false, applied, revision: '2', reductionDb: 0, addedLatencySamples,
});
beforeEach(() => { vi.useFakeTimers({ toFake: ['setInterval', 'clearInterval'] }); vi.mocked(listen).mockClear(); });
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.useRealTimers(); });
it('読取りでは有効化せず、自分用の遅延が0である説明と保証範囲を出す', async () => {
    const request = vi.spyOn(broadcastTruePeakApi, 'request').mockImplementation(async config => ({ ...fixture(), config: config ?? fixture().config, applied: config?.enabled ?? false, addedLatencySamples: config?.enabled ? 48 : 0 }));
    render(<BroadcastTruePeakPanel />); await act(async () => {});
    expect(request).toHaveBeenCalledWith();
    expect(request.mock.calls.every(args => args.length === 0)).toBe(true);
    const detailsSummary = screen.getByText(message('ja', 'peak.details'));
    const limitsSummary = screen.getByText(message('ja', 'truePeak.limitsTitle'));
    expect(detailsSummary.className).toBe(limitsSummary.className);
    expect(detailsSummary.closest('details')).not.toHaveAttribute('open');
    expect(screen.getByRole('spinbutton', { name: message('ja', 'truePeak.ceiling') })).toHaveValue(-3);
    expect(screen.getByText(message('ja', 'truePeak.lead'))).toBeInTheDocument();
    expect(screen.getByText(/自分用は 0 sample/)).toBeInTheDocument();
    fireEvent.click(screen.getByText(message('ja', 'truePeak.limitsTitle')));
    expect(screen.getByText(/OBS 内部の処理/)).toBeInTheDocument();
    expect(screen.getByText(/デバイス側のサンプルレート変換は範囲外/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole('switch', { name: message('ja', 'truePeak.title') })); await act(async () => {});
    expect(request).toHaveBeenCalledWith({ enabled: true, ceilingDb: -3, releaseMs: 150 });
    expect(screen.getByText(/48 sample/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole('switch', { name: message('ja', 'truePeak.title') })); await act(async () => {});
    expect(request).toHaveBeenLastCalledWith({ enabled: false, ceilingDb: -3, releaseMs: 150 });
    expect(screen.queryByText(message('ja', 'truePeak.notApplied'))).not.toBeInTheDocument();
});
it('音楽鑑賞ではOFFと未取得を出さず、ONのときはOFFへ戻せる', async () => {
    const request = vi.spyOn(broadcastTruePeakApi, 'request').mockResolvedValue(fixture(false));
    render(<BroadcastTruePeakPanel music />);
    await act(async () => {});
    expect(screen.queryByRole('region', { name: message('ja', 'truePeak.title') })).not.toBeInTheDocument();
    request.mockResolvedValue(fixture(true));
    await act(async () => { await vi.advanceTimersByTimeAsync(500); });
    expect(screen.getByRole('region', { name: message('ja', 'truePeak.title') })).toBeInTheDocument();
    fireEvent.click(screen.getByRole('switch', { name: message('ja', 'truePeak.title') }));
    await act(async () => {});
    expect(request).toHaveBeenLastCalledWith(expect.objectContaining({ enabled: false }));
});
it('有効でも分離出力でないときは未適用と遅延 0 を出す', async () => {
    vi.spyOn(broadcastTruePeakApi, 'request').mockResolvedValue(fixture(true, 0, false));
    render(<BroadcastTruePeakPanel />); await act(async () => {});
    expect(screen.getByText(message('ja', 'truePeak.notApplied'))).toBeInTheDocument();
    expect(screen.getByText(/先読み：0 sample/)).toBeInTheDocument();
});
it('本番保護の間はスイッチ・数値・適用を止めて理由を示し、解除すると書き込める', async () => {
    const request = vi.spyOn(broadcastTruePeakApi, 'request').mockImplementation(async config => ({ ...fixture(), config: config ?? fixture().config, applied: config?.enabled ?? false, addedLatencySamples: config?.enabled ? 48 : 0 }));
    const view = render(<BroadcastTruePeakPanel locked />); await act(async () => {});
    const reason = screen.getByText(message('ja', 'peak.liveLocked'));
    const toggle = screen.getByRole('switch', { name: message('ja', 'truePeak.title') });
    expect(toggle).toBeDisabled();
    expect(toggle).toHaveAttribute('aria-describedby', reason.id);
    expect(screen.getByRole('spinbutton', { name: message('ja', 'truePeak.ceiling') })).toBeDisabled();
    expect(screen.getByRole('spinbutton', { name: message('ja', 'truePeak.release') })).toBeDisabled();
    const apply = screen.getByRole('button', { name: message('ja', 'truePeak.apply') });
    expect(apply).toBeDisabled();
    // ON と OFF はスイッチだけが示す。稼働中で反映待ちでも停止でもないときは、状態の行を出さない（#589）。
    expect(screen.queryByRole('status')).not.toBeInTheDocument();
    fireEvent.click(toggle);
    fireEvent.click(apply);
    await act(async () => {});
    expect(request.mock.calls.every(args => args.length === 0)).toBe(true);
    await act(async () => { view.rerender(<BroadcastTruePeakPanel locked={false} />); });
    expect(screen.queryByText(message('ja', 'peak.liveLocked'))).not.toBeInTheDocument();
    const unlocked = screen.getByRole('switch', { name: message('ja', 'truePeak.title') });
    expect(unlocked).toBeEnabled();
    expect(unlocked).not.toHaveAttribute('aria-describedby');
    expect(screen.getByRole('spinbutton', { name: message('ja', 'truePeak.ceiling') })).toBeEnabled();
    expect(screen.getByRole('spinbutton', { name: message('ja', 'truePeak.release') })).toBeEnabled();
    const applyAgain = screen.getByRole('button', { name: message('ja', 'truePeak.apply') });
    expect(applyAgain).toBeEnabled();
    fireEvent.click(unlocked); await act(async () => {});
    expect(request).toHaveBeenCalledWith({ enabled: true, ceilingDb: -3, releaseMs: 150 });
    fireEvent.click(applyAgain); await act(async () => {});
    expect(request.mock.calls.filter(args => args.length > 0)).toHaveLength(2);
});
it('ONとOFFの文字は出さず、数値と抑制量は数値の詳細のときだけ、状態の行は読めない・反映途中・停止のときだけ出す', async () => {
    const request = vi.spyOn(broadcastTruePeakApi, 'request').mockResolvedValue(fixture(true));
    const view = render(<BroadcastTruePeakPanel />); await act(async () => {});
    const region = screen.getByRole('region', { name: message('ja', 'truePeak.title') });
    expect(screen.queryByRole('status')).not.toBeInTheDocument();
    expect(region).not.toHaveTextContent('dBFS /');
    expect(region).not.toHaveTextContent(message('ja', 'truePeak.reduction', { db: '0.0' }));
    // 先読みの説明は数値の詳細とは別で、これまでどおり出す。
    expect(screen.getByText(/48 sample/)).toBeInTheDocument();
    await act(async () => { view.rerender(<BroadcastTruePeakPanel numericDetails />); });
    expect(screen.getByText('-3.0 dBFS / 150 ms')).toBeInTheDocument();
    expect(screen.getByText(message('ja', 'truePeak.reduction', { db: '0.0' }))).toBeInTheDocument();
    expect(screen.queryByRole('status')).not.toBeInTheDocument();
    request.mockResolvedValue({ ...fixture(true), pending: true, running: false, reductionDb: 1.2 });
    await act(async () => { await vi.advanceTimersByTimeAsync(500); });
    const status = screen.getByRole('status');
    expect(status).toHaveTextContent(`${message('ja', 'truePeak.pending')} · ${message('ja', 'truePeak.stopped')}`);
    expect(status).not.toHaveTextContent('ON');
    expect(status).not.toHaveTextContent('OFF');
    expect(screen.getByText(message('ja', 'truePeak.reduction', { db: '1.2' }))).toBeInTheDocument();
    request.mockRejectedValue(new Error('down'));
    await act(async () => { await vi.advanceTimersByTimeAsync(500); });
    expect(screen.getByRole('status')).toHaveTextContent(message('ja', 'truePeak.unknown'));
    expect(screen.queryByText(/dBFS \//)).not.toBeInTheDocument();
    expect(screen.queryByText(message('ja', 'truePeak.reduction', { db: '1.2' }))).not.toBeInTheDocument();
});
